-- ------------------------------------------------------------------------------
-- TEST 4: Verification of Triggers & Data Flow (Safe Test Ad & Cleanup)
-- ------------------------------------------------------------------------------
DO $$
DECLARE
    v_user_id UUID := gen_random_uuid();
    v_city_id UUID;
    v_brand_id UUID;
    v_model_id UUID;
    v_ad_id UUID;
BEGIN
    -- Get IDs from seed data
    SELECT id INTO v_city_id FROM cities WHERE slug = 'karachi' LIMIT 1;
    SELECT id INTO v_brand_id FROM brands WHERE slug = 'apple' LIMIT 1;
    SELECT id INTO v_model_id FROM models WHERE slug = 'iphone-15' AND brand_id = v_brand_id LIMIT 1;

    -- 1. Create a dummy test profile
    INSERT INTO profiles (id, full_name) VALUES (v_user_id, 'Test Seller MobileBazar');
    INSERT INTO profile_private (id, phone, role) VALUES (v_user_id, '+923000000001', 'user');

    -- 2. Insert test ad
    INSERT INTO ads (
        id, seller_id, brand_id, model_id, city_id,
        title, description, price, condition, pta_status,
        storage_gb, battery_health, warranty_type, warranty_months_remaining
    ) VALUES (
        gen_random_uuid(), v_user_id, v_brand_id, v_model_id, v_city_id,
        'iPhone 15 128GB Factory PTA Approved',
        'Box pack phone, pristine condition 100% battery',
        235000, 'used', 'pta_approved',
        128, 100, 'in_warranty', 6
    ) RETURNING id INTO v_ad_id;

    -- 3. Check profile ads_count incremented
    IF (SELECT ads_count FROM profiles WHERE id = v_user_id) != 1 THEN
        RAISE EXCEPTION 'Test Failed: profiles.ads_count was not incremented by trigger!';
    END IF;

    -- 4. Insert private IMEI
    INSERT INTO ad_private (ad_id, imei) VALUES (v_ad_id, '354890123456789');

    -- 5. Insert Image position 0 (Cover)
    INSERT INTO ad_images (ad_id, storage_path, position) VALUES (v_ad_id, 'ads/test/cover.webp', 0);

    -- 6. Add a favorite
    INSERT INTO favorites (user_id, ad_id) VALUES (v_user_id, v_ad_id);

    -- 7. Check favorites_count incremented
    IF (SELECT favorites_count FROM ads WHERE id = v_ad_id) != 1 THEN
        RAISE EXCEPTION 'Test Failed: ads.favorites_count was not incremented by trigger!';
    END IF;

    -- 8. Verify Search Vector generated
    IF (SELECT search_vector FROM ads WHERE id = v_ad_id) IS NULL THEN
        RAISE EXCEPTION 'Test Failed: search_vector was not generated by trigger!';
    END IF;

    -- Cleanup test data
    DELETE FROM profiles WHERE id = v_user_id; -- Cascades and deletes ad, private, images, favorites!
    
    RAISE NOTICE 'SUCCESS: All triggers, constraints, and cascades executed perfectly!';
END $$;

